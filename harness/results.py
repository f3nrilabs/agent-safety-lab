"""JSONL and summary writers, matching ``results/README.md``.

One file per batch: ``results/<suite>-<model-slug>-<defense>-<YYYYMMDD>.jsonl``, one JSON
object per run. A ``summary.md`` next to it reports per-scenario rates and the exact
command that produced them. Nothing here runs automatically; callers must have executed
the runs first.
"""

from __future__ import annotations

import json
import re
from collections import Counter
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from .agent import RunTranscript
from .scorer import Score

#: Keys required by ``results/README.md``; ``task_signal`` and ``outcome`` are additive
#: fields that explain the two booleans without changing the documented ones.
RESULT_FIELDS: tuple[str, ...] = (
    "scenario",
    "suite",
    "model",
    "provider",
    "base_url",
    "defense",
    "date",
    "run",
    "runs_total",
    "turns",
    "attack_success",
    "attack_signal",
    "task_success",
    "task_signal",
    "final_answer_excerpt",
    "outcome",
)

EXCERPT_CHARS = 280


def utc_now() -> str:
    """UTC timestamp in the format used by the results files (``...Z``)."""
    return datetime.now(tz=UTC).strftime("%Y-%m-%dT%H:%M:%SZ")


def model_slug(model_id: str) -> str:
    """Filesystem-safe slug for a model id (``claude-sonnet-4-5`` stays readable)."""
    slug = re.sub(r"[^a-z0-9]+", "-", model_id.lower()).strip("-")
    return slug or "model"


def batch_path(out_dir: Path | str, suite: str, model_id: str, defense: str, date: str) -> Path:
    """``<out>/<suite>-<model-slug>-<defense>-<YYYYMMDD>.jsonl``."""
    day = date[:10].replace("-", "")
    return Path(out_dir) / f"{suite}-{model_slug(model_id)}-{defense}-{day}.jsonl"


def excerpt(text: str, limit: int = EXCERPT_CHARS) -> str:
    """Single-line excerpt; the summary only ever quotes text that appears verbatim here."""
    flat = " ".join(text.split())
    if len(flat) <= limit:
        return flat
    return flat[: limit - 1].rstrip() + "…"


def build_record(
    transcript: RunTranscript,
    score: Score,
    *,
    run: int,
    runs_total: int,
    date: str,
    base_url: str | None = None,
) -> dict[str, Any]:
    """One JSONL line for one run."""
    record: dict[str, Any] = {
        "scenario": transcript.scenario_id,
        "suite": transcript.suite,
        "model": transcript.model_id,
        "provider": transcript.provider,
        "base_url": base_url if transcript.provider == "openai" else "",
        "defense": transcript.defense,
        "date": date,
        "run": run,
        "runs_total": runs_total,
        "turns": transcript.turns,
        "attack_success": score.attack_success,
        "attack_signal": score.attack_signal,
        "task_success": score.task_success,
        "task_signal": score.task_signal,
        "final_answer_excerpt": excerpt(transcript.final_answer),
        "outcome": score.outcome,
    }
    return {field: record[field] for field in RESULT_FIELDS}


class BatchWriter:
    """Appends run records to one batch file and writes its human summary."""

    def __init__(
        self,
        out_dir: Path | str,
        *,
        suite: str,
        model_id: str,
        defense: str,
        date: str | None = None,
    ) -> None:
        self.out_dir = Path(out_dir)
        self.suite = suite
        self.model_id = model_id
        self.defense = defense
        self.date = date or utc_now()
        self.path = batch_path(self.out_dir, suite, model_id, defense, self.date)
        self.summary_path = self.path.with_suffix(".summary.md")
        self.records: list[dict[str, Any]] = []

    def append(self, record: dict[str, Any]) -> None:
        """Write one record immediately so a crash does not lose earlier runs."""
        missing = [field for field in RESULT_FIELDS if field not in record]
        if missing:
            raise ValueError(f"result record missing fields: {', '.join(missing)}")
        self.out_dir.mkdir(parents=True, exist_ok=True)
        with self.path.open("a", encoding="utf-8", newline="\n") as handle:
            handle.write(json.dumps({field: record[field] for field in RESULT_FIELDS}))
            handle.write("\n")
        self.records.append(record)

    def write_summary(self, command: str) -> Path:
        """Write the per-scenario summary next to the JSONL file."""
        by_scenario: dict[str, list[dict[str, Any]]] = {}
        for record in self.records:
            by_scenario.setdefault(str(record["scenario"]), []).append(record)

        lines = [
            f"# Results: {self.suite} / {self.model_id} / defense `{self.defense}`",
            "",
            f"- Date: {self.date}",
            f"- Command: `{command}`",
            "- Source: generated by `python -m harness`; every number below comes from the "
            "JSONL file next to this summary.",
            "",
            "| scenario | runs | attack success | task success | outcomes |",
            "| -------- | ---- | -------------- | ------------ | -------- |",
        ]
        for scenario_id, records in sorted(by_scenario.items()):
            total = len(records)
            attacks = sum(1 for record in records if record["attack_success"])
            tasks = sum(1 for record in records if record["task_success"])
            outcomes = Counter(str(record["outcome"]) for record in records)
            outcome_text = ", ".join(
                f"{name} ({count})" for name, count in sorted(outcomes.items())
            )
            lines.append(
                f"| {scenario_id} | {total} | {attacks}/{total} | {tasks}/{total} "
                f"| {outcome_text} |"
            )
        lines.append("")
        self.summary_path.write_text("\n".join(lines), encoding="utf-8", newline="\n")
        return self.summary_path
